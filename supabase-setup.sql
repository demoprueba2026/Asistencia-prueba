-- ------------------------------------------------------------------------------
-- 1. TABLA: students (Estudiantes, Notas, Pagos y Asistencia acumulada)
-- ------------------------------------------------------------------------------
create table if not exists public.students (
  id text primary key,
  name text not null,
  cedula text,
  email text,
  phone text,
  year integer not null default 1,
  status text not null default '',
  "BoletaVisible" text not null default 'NO',
  payments jsonb not null default '{}'::jsonb,
  payment_status text not null default 'no_pago',
  paid_amount numeric not null default 0,
  attendance jsonb not null default '{}'::jsonb,
  attendance_by_date jsonb not null default '{}'::jsonb,
  grades jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

-- Asegurar que todas las columnas existan por si la tabla ya había sido creada parcialmente:
alter table public.students add column if not exists name text;
alter table public.students add column if not exists cedula text;
alter table public.students add column if not exists email text;
alter table public.students add column if not exists phone text;
alter table public.students add column if not exists year integer not null default 1;
alter table public.students add column if not exists status text not null default '';
alter table public.students add column if not exists "BoletaVisible" text not null default 'NO';
alter table public.students add column if not exists payments jsonb not null default '{}'::jsonb;
alter table public.students add column if not exists payment_status text not null default 'no_pago';
alter table public.students add column if not exists paid_amount numeric not null default 0;
alter table public.students add column if not exists attendance jsonb not null default '{}'::jsonb;
alter table public.students add column if not exists attendance_by_date jsonb not null default '{}'::jsonb;
alter table public.students add column if not exists grades jsonb not null default '{}'::jsonb;
alter table public.students add column if not exists created_at timestamptz not null default now();

-- ------------------------------------------------------------------------------
-- 2. TABLA: attendances (Registros diarios de asistencia por materia)
-- ------------------------------------------------------------------------------
create table if not exists public.attendances (
  id bigint generated by default as identity primary key,
  student_id text not null references public.students(id) on delete cascade,
  date date not null,
  subject text not null,
  subject_label text,
  status text not null check (status in ('asistente', 'inasistente')),
  email_sent_at timestamptz,
  created_at timestamptz not null default now(),
  unique (student_id, date, subject)
);

-- Asegurar columnas y restricciones en attendances por si ya existía:
alter table public.attendances add column if not exists subject_label text;
alter table public.attendances add column if not exists email_sent_at timestamptz;
alter table public.attendances add column if not exists created_at timestamptz not null default now();

do $$
begin
  if not exists (
    select 1 from pg_constraint where conname = 'attendances_student_id_date_subject_key'
  ) then
    begin
      alter table public.attendances add constraint attendances_student_id_date_subject_key unique (student_id, date, subject);
    exception
      when duplicate_table or duplicate_object then null;
    end;
  end if;
end $$;

-- ------------------------------------------------------------------------------
-- 3. ÍNDICES DE RENDIMIENTO (Búsquedas rápidas por año, fecha y cédula)
-- ------------------------------------------------------------------------------
create index if not exists idx_students_year_name on public.students (year, name asc);
create index if not exists idx_students_cedula on public.students (cedula);
create index if not exists idx_attendances_date on public.attendances (date);
create index if not exists idx_attendances_date_email on public.attendances (date, email_sent_at);
create index if not exists idx_attendances_student_id on public.attendances (student_id);

